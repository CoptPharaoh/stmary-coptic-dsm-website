import { createHash } from "node:crypto";
import { readFile, readdir, writeFile, access } from "node:fs/promises";
import { basename, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const library = resolve(root, "assets/books");
const readJson = async (name) => JSON.parse(await readFile(resolve(library, name), "utf8"));
const [authors, metadata, inventory] = await Promise.all([
  readJson("authors.json"), readJson("metadata.json"), readJson("migration-inventory.json"),
]);
const existing = new Map(inventory.files.map(({ path, sha256 }) => [
  path.replace("assets/books/", "").replace("/pope-shenouda/", "/pope-shenouda-iii/"), sha256,
]));
const collator = new Intl.Collator(["en", "ar"], { numeric: true, sensitivity: "base" });
const seen = new Map();
const books = [];
const stats = { files: 0, duplicates: 0, review: 0 };

async function* pdfs(folder, prefix = "") {
  const entries = await readdir(resolve(library, folder), { withFileTypes: true });
  const copy = (name) => / \(\d+\)\.pdf$/i.test(name);
  entries.sort((a, b) => Number(copy(a.name)) - Number(copy(b.name)) ||
    (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
  for (const entry of entries) {
    if (entry.name.startsWith(".")) continue;
    const next = prefix + entry.name;
    if (entry.isDirectory()) yield* pdfs(folder + "/" + entry.name, next + "/");
    else if (entry.isFile() && /\.pdf$/i.test(entry.name)) yield next;
  }
}

function filenameTitle(path) {
  const name = basename(path, basename(path).slice(-4)).normalize("NFC")
    .replace(/\s*-\s*Arabic(?:\s*\(\d+\))?$/i, "")
    .replace(/[-_]+/g, " ").replace(/\bv(\d+)\b/gi, (_, n) => "Volume " + Number(n))
    .replace(/\bqanda\b/gi, "Q&A").replace(/\s+/g, " ").trim();
  return name === name.toLowerCase() ? name.replace(/\b[a-z]/g, (char) => char.toUpperCase()) : name;
}

for (const language of ["english", "arabic"]) {
  for await (const path of pdfs(language)) {
    stats.files++;
    const key = language + "/" + path;
    const authorId = path.split("/")[0];
    const author = Object.hasOwn(authors, authorId) && authors[authorId];
    const override = Object.hasOwn(metadata, key) ? metadata[key] : {};
    if (!path.includes("/") || !author || (authorId === "other-authors" && !override.authorName)) {
      console.warn("Unidentified or misplaced PDF:", key);
      stats.review++;
      continue;
    }
    const data = await readFile(resolve(library, key));
    const sha = createHash("sha256").update(data).digest("hex");
    if (existing.get(key) !== sha && (override.distributionStatus !== "approved" || !override.permission?.trim())) {
      console.warn("Not cataloged: distribution approval required:", key);
      stats.review++;
      continue;
    }
    if (seen.has(sha)) {
      console.warn("Duplicate PDF retained:", seen.get(sha), "=", key);
      stats.duplicates++;
      continue;
    }
    seen.set(sha, key);
    const title = override.title || filenameTitle(path);
    const pdf = "assets/books/" + key.split("/").map(encodeURIComponent).join("/");
    if (override.cover) await access(resolve(root, override.cover));
    books.push({
      id: createHash("sha256").update(key).digest("hex").slice(0, 24),
      title, titleLanguage: override.titleLanguage || (/\p{Script=Arabic}/u.test(title) ? "ar" : "en"),
      alternateTitle: override.title ? filenameTitle(path) : undefined,
      authorId, authorName: override.authorName || author.name, language, pdf,
      bytes: data.length,
      description: override.description, subject: override.subject, cover: override.cover,
      publication: override.publication, publisher: override.publisher, sourceUrl: override.sourceUrl,
      distributionStatus: override.distributionStatus || "unverified", permission: override.permission,
    });
  }
}

books.sort((a, b) => collator.compare(a.title, b.title) || (a.pdf < b.pdf ? -1 : a.pdf > b.pdf ? 1 : 0));
const activeAuthors = Object.fromEntries(Object.entries(authors).filter(([id]) => books.some((book) => book.authorId === id)));
for (const author of Object.values(activeAuthors)) {
  if (author.portrait) await access(resolve(root, author.portrait));
}
const output = JSON.stringify({ authors: activeAuthors, books }, null, 2);
const browserOutput = output.replace(/</g, "\\u003c").replace(/[\u2028\u2029]/g, (char) => "\\u" + char.charCodeAt(0).toString(16));
await writeFile(resolve(library, "catalog.json"), output + "\n");
// A classic script lets the same catalog load from file:// as well as HTTP.
await writeFile(resolve(library, "catalog.js"), "// Generated by scripts/generate-book-catalog.mjs.\nwindow.orthodoxBookCatalog = " + browserOutput + ";\n");
console.log(`${stats.files} PDFs; ${books.length} cataloged; ${stats.duplicates} duplicate copies; ${stats.review} withheld for review.`);
